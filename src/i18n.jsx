const LanguageContext = createContext(null)

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState('en')
  const t = useCallback((key, vars) => {
    let str = PROVENANCE_LABELS[key] ?? translations[lang][key] ?? translations.en[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), v)
    return str
  }, [lang])
  return (
    <LanguageContext.Provider value={{ lang, setLang, t, translations: translations[lang] }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLang() {
  const ctx = useContext(LanguageContext)
  if (!ctx) throw new Error('useLang must be used within LanguageProvider')
  return ctx
}
